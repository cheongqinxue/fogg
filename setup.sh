#!/usr/bin/env bash
# Bootstrap FOGG dev tools into .tools/ (isolated from system Python, uv, Flutter).
# Does not modify ~/.bashrc or global installs. Re-run safely.
#
# Usage:
#   ./setup.sh
#   source .tools/env.sh    # then: uv run pytest, flutter run, etc.

set -euo pipefail

FOGG_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
TOOLS_DIR="${FOGG_ROOT}/.tools"
UV_DIR="${TOOLS_DIR}/uv"
FLUTTER_DIR="${TOOLS_DIR}/flutter"
PYTHON_MANAGED_DIR="${TOOLS_DIR}/python"
UV_CACHE_DIR="${TOOLS_DIR}/uv-cache"
ENV_FILE="${TOOLS_DIR}/env.sh"

# Match pyproject.toml requires-python (install latest 3.13.x uv manages).
PYTHON_VERSION="${FOGG_PYTHON_VERSION:-3.13}"

log() {
  printf '==> %s\n' "$*"
}

warn() {
  printf 'warning: %s\n' "$*" >&2
}

die() {
  printf 'error: %s\n' "$*" >&2
  exit 1
}

require_cmd() {
  local name="$1"
  command -v "$name" >/dev/null 2>&1 || die "Missing required command: ${name}. Install it with your OS package manager and re-run."
}

write_env_file() {
  mkdir -p "${TOOLS_DIR}"
  cat >"${ENV_FILE}" <<EOF
# Generated by setup.sh — source from repo root:
#   source .tools/env.sh
FOGG_ROOT='${FOGG_ROOT}'
export FOGG_ROOT
export PATH='${UV_DIR}:${FLUTTER_DIR}/bin:'"\${PATH}"
export UV_PYTHON_INSTALL_DIR='${PYTHON_MANAGED_DIR}'
export UV_CACHE_DIR='${UV_CACHE_DIR}'
export FLUTTER_ROOT='${FLUTTER_DIR}'
export PUB_CACHE='${TOOLS_DIR}/pub-cache'
EOF
}

install_uv() {
  local uv_bin="${UV_DIR}/uv"
  if [[ -x "${uv_bin}" ]]; then
    log "uv already present at ${uv_bin} ($("${uv_bin}" --version))"
    return 0
  fi
  log "Installing uv into ${UV_DIR} (project-local, no PATH changes)"
  mkdir -p "${UV_DIR}"
  require_cmd curl
  curl -fsSL https://astral.sh/uv/install.sh | env \
    UV_UNMANAGED_INSTALL="${UV_DIR}" \
    UV_NO_MODIFY_PATH=1 \
    sh
  [[ -x "${uv_bin}" ]] || die "uv install failed: ${uv_bin} not found"
}

install_managed_python() {
  log "Installing managed Python ${PYTHON_VERSION} into ${PYTHON_MANAGED_DIR}"
  mkdir -p "${PYTHON_MANAGED_DIR}" "${UV_CACHE_DIR}"
  export UV_PYTHON_INSTALL_DIR="${PYTHON_MANAGED_DIR}"
  export UV_CACHE_DIR="${UV_CACHE_DIR}"
  "${UV_DIR}/uv" python install "${PYTHON_VERSION}"
}

sync_backend() {
  log "Creating/updating .venv and syncing backend (uv sync --extra dev)"
  export UV_PYTHON_INSTALL_DIR="${PYTHON_MANAGED_DIR}"
  export UV_CACHE_DIR="${UV_CACHE_DIR}"
  cd "${FOGG_ROOT}"
  "${UV_DIR}/uv" sync --extra dev --python "${PYTHON_VERSION}"
}

install_flutter() {
  local flutter_bin="${FLUTTER_DIR}/bin/flutter"
  if [[ -x "${flutter_bin}" ]]; then
    log "Flutter already present at ${FLUTTER_DIR} ($("${flutter_bin}" --version | head -1))"
    return 0
  fi
  require_cmd git
  log "Cloning Flutter (stable) into ${FLUTTER_DIR} — this may take a few minutes"
  git clone https://github.com/flutter/flutter.git -b stable --depth 1 "${FLUTTER_DIR}"
  [[ -x "${flutter_bin}" ]] || die "Flutter clone failed: ${flutter_bin} not found"
}

bootstrap_flutter() {
  export PATH="${FLUTTER_DIR}/bin:${PATH}"
  export FLUTTER_ROOT="${FLUTTER_DIR}"
  export PUB_CACHE="${TOOLS_DIR}/pub-cache"
  mkdir -p "${PUB_CACHE}"

  log "Flutter precache (web + Linux host tools)"
  "${FLUTTER_DIR}/bin/flutter" config --no-analytics >/dev/null 2>&1 || true
  "${FLUTTER_DIR}/bin/flutter" precache --web

  log "Resolving frontend packages"
  cd "${FOGG_ROOT}/frontend"
  "${FLUTTER_DIR}/bin/flutter" pub get

  log "Flutter doctor (informational)"
  "${FLUTTER_DIR}/bin/flutter" doctor || warn "flutter doctor reported issues; you may still run web builds."
}

install_gitleaks() {
  local gitleaks_bin="${TOOLS_DIR}/gitleaks/gitleaks"
  if [[ -x "${gitleaks_bin}" ]]; then
    log "gitleaks already present at ${gitleaks_bin}"
    return 0
  fi
  log "Installing gitleaks into ${TOOLS_DIR}/gitleaks"
  bash "${FOGG_ROOT}/scripts/install-gitleaks.sh"
}

install_pre_commit_hooks() {
  log "Installing git pre-commit hooks (uv run pre-commit install)"
  cd "${FOGG_ROOT}"
  export UV_PYTHON_INSTALL_DIR="${PYTHON_MANAGED_DIR}"
  export UV_CACHE_DIR="${UV_CACHE_DIR}"
  "${UV_DIR}/uv" run pre-commit install
}

main() {
  log "FOGG root: ${FOGG_ROOT}"
  require_cmd curl
  require_cmd git

  install_uv
  write_env_file
  # shellcheck source=/dev/null
  source "${ENV_FILE}"

  install_managed_python
  sync_backend
  install_flutter
  bootstrap_flutter
  install_gitleaks
  install_pre_commit_hooks

  log "Done."
  printf '\n'
  printf 'Add tools to your current shell:\n'
  printf '  source %s\n' "${ENV_FILE}"
  printf '\n'
  printf 'Then try:\n'
  printf '  uv run pytest tests/\n'
  printf '  cd frontend && flutter run -d chrome\n'
  printf '  uv run pre-commit run --all-files   # optional manual check\n'
  printf '\n'
  printf 'Project-local installs live under %s (safe to delete to reset).\n' "${TOOLS_DIR}"
}

main "$@"
